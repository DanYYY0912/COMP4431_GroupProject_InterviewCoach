import { chromium } from '@playwright/test';
import fs from 'node:fs/promises';
const browser = await chromium.launch();
const page = await browser.newPage({viewport:{width:1440,height:1100},reducedMotion:'reduce'});
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.goto('http://127.0.0.1:8000');
await page.getByRole('button',{name:'Start a practice interview'}).waitFor();
await page.screenshot({path:'../artifacts/verification/dashboard.png',fullPage:true});
await page.getByRole('button',{name:'Start a practice interview'}).click();
await page.screenshot({path:'../artifacts/verification/setup.png',fullPage:true});
await page.goto('http://127.0.0.1:8000/#/methodology');
await page.getByText('Inspect the saved QLoRA configuration', {exact:true}).waitFor();
await page.getByText('Active retrieval', {exact:true}).waitFor();
await page.screenshot({path:'../artifacts/verification/methodology.png',fullPage:true});
await fs.writeFile('../artifacts/verification/final-ui.json', JSON.stringify({page_errors:errors},null,2));
await browser.close();
if (errors.length) throw new Error(`Browser errors: ${errors.join('; ')}`);
