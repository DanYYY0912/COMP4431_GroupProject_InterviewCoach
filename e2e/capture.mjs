import { chromium, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import fs from 'node:fs/promises';
const browser = await chromium.launch();
const context = await browser.newContext({viewport:{width:1440,height:1100},reducedMotion:'reduce'});
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.goto('http://127.0.0.1:8000');
await page.getByRole('heading',{name:'Practice interview',exact:true}).waitFor();
await expect(page.getByRole('button',{name:'Start my interview'})).toBeDisabled();
await page.getByText('Checking services…').waitFor({state:'hidden'});
await page.screenshot({path:'../artifacts/verification/setup.png',fullPage:true});
await page.getByRole('button',{name:'Try a sample role'}).click();
await expect(page.getByRole('button',{name:'Start my interview'})).toBeEnabled();
await expect(page.getByRole('complementary',{name:'Configuration status'}).locator('input,select,textarea')).toHaveCount(0);
await page.screenshot({path:'../artifacts/verification/setup-ready.png',fullPage:true});
const desktopAccessibility = await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa']).analyze();
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'../artifacts/verification/setup-mobile.png',fullPage:true});
const mobileAccessibility = await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa']).analyze();
const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
await page.setViewportSize({width:1440,height:1100});
await page.goto('http://127.0.0.1:8000/#/settings');
await page.getByLabel('Agent base URL', {exact:true}).waitFor();
await page.getByLabel('Reranker model', {exact:true}).waitFor();
await page.screenshot({path:'../artifacts/verification/inference-settings.png',fullPage:true});
const violations = [...desktopAccessibility.violations,...mobileAccessibility.violations].map(({id})=>id);
await fs.writeFile('../artifacts/verification/final-ui.json', JSON.stringify({page_errors:errors,accessibility_violations:violations,mobile_overflow:overflow},null,2));
await browser.close();
expect(errors).toEqual([]);
expect(violations).toEqual([]);
expect(overflow).toBe(false);
